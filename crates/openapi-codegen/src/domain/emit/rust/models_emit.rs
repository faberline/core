//! Emit serde structs / aliases for the spec's component schemas.

use std::collections::BTreeSet;

use crate::domain::emit::rust::rsmap;
use crate::domain::ir::names::{to_pascal, to_snake, NameRegistry};
use crate::domain::ir::openapi::{RefOr, Schema, Spec};
use crate::domain::ir::typemap::TypeMap;
use crate::domain::RustTarget;

pub const HEADER: &str = "// Code generated by openapi-codegen. DO NOT EDIT.\n";

const RUST_KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false", "fn",
    "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
    "return", "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe",
    "use", "where", "while", "async", "await", "box", "do", "macro", "try", "yield",
];

/// `(rust_field_name, serde_rename)` — the rename is `Some` when the field name
/// differs from the JSON key.
pub fn field_name(key: &str, target: RustTarget) -> (String, Option<String>) {
    let snake = to_snake(key);
    let field =
        if RUST_KEYWORDS.contains(&snake.as_str()) || (target.reserves_gen() && snake == "gen") {
            format!("{snake}_")
        } else {
            snake
        };
    let rename = (field != key).then(|| key.to_string());
    (field, rename)
}

pub fn emit(spec: &Spec, tm: &TypeMap, target: RustTarget) -> String {
    emit_with_warnings(spec, tm, target).0
}

/// Like [`emit`], and also returns one warning per schema that stays `serde_json::Value`.
pub fn emit_with_warnings(spec: &Spec, tm: &TypeMap, target: RustTarget) -> (String, Vec<String>) {
    let mut out = String::from(HEADER);
    out.push_str("use serde::{Deserialize, Serialize};\n");

    let mut warnings = Vec::new();
    let mut blocks: Vec<String> = Vec::new();
    for (key, node) in &spec.components.schemas {
        let name = tm.names.get(key).cloned().unwrap_or_else(|| to_pascal(key));
        blocks.push(emit_schema(
            key,
            &name,
            node,
            spec,
            tm,
            target,
            &mut warnings,
        ));
    }
    if !blocks.is_empty() {
        out.push('\n');
        out.push_str(&blocks.join("\n"));
    }
    (out, warnings)
}

fn emit_schema(
    key: &str,
    name: &str,
    node: &RefOr<Schema>,
    spec: &Spec,
    tm: &TypeMap,
    target: RustTarget,
    warnings: &mut Vec<String>,
) -> String {
    match node {
        RefOr::Ref(_) => format!("pub type {name} = {};\n", rsmap::type_expr(node, tm)),
        RefOr::Item(schema) if is_string_enum(schema) => emit_enum(name, schema),
        RefOr::Item(schema) if is_union(schema) => {
            emit_union(key, name, schema, spec, tm, target, warnings)
        }
        RefOr::Item(schema) if schema.properties.is_empty() => {
            format!("pub type {name} = {};\n", rsmap::type_expr(node, tm))
        }
        RefOr::Item(schema) => emit_struct(name, schema, tm, target),
    }
}

const SCHEMAS_PREFIX: &str = "#/components/schemas/";

/// A component `oneOf` / `anyOf` with no own properties, enum or `allOf`.
fn is_union(schema: &Schema) -> bool {
    (!schema.one_of.is_empty() || !schema.any_of.is_empty())
        && schema.properties.is_empty()
        && schema.all_of.is_empty()
        && schema.enum_values.is_empty()
}

fn is_null_branch(branch: &RefOr<Schema>) -> bool {
    matches!(branch, RefOr::Item(s) if s.ty.0.as_slice() == ["null"])
}

/// The struct component a `$ref` points to (not a string enum, has properties).
fn struct_component<'a>(spec: &'a Spec, reference: &str) -> Option<&'a Schema> {
    let key = reference.strip_prefix(SCHEMAS_PREFIX)?;
    match spec.components.schemas.get(key)? {
        RefOr::Item(s) if !s.properties.is_empty() && !is_string_enum(s) => Some(&**s),
        _ => None,
    }
}

/// `(json type, Rust variant, payload type)` for a single-type primitive branch.
fn primitive_branch(s: &Schema) -> Option<(&'static str, &'static str, &'static str)> {
    if !s.enum_values.is_empty()
        || !s.properties.is_empty()
        || !s.one_of.is_empty()
        || !s.any_of.is_empty()
        || !s.all_of.is_empty()
    {
        return None;
    }
    match s.type_names().as_slice() {
        [t] => match t.as_str() {
            "string" => Some(("string", "String", "String")),
            "integer" => Some(("integer", "Integer", "i64")),
            "number" => Some(("number", "Number", "f64")),
            "boolean" => Some(("boolean", "Boolean", "bool")),
            _ => None,
        },
        _ => None,
    }
}

enum UnionPlan {
    /// Internally tagged by the discriminator property.
    Tagged(String),
    /// Untagged: serde tries each variant in declared order.
    Untagged,
    /// Cannot be told apart: stays `serde_json::Value`.
    Ambiguous,
}

fn union_plan(schema: &Schema, branches: &[&RefOr<Schema>], spec: &Spec) -> UnionPlan {
    if branches.len() < 2 {
        return UnionPlan::Ambiguous;
    }
    if let Some(d) = &schema.discriminator {
        // serde removes the tag before it reads the variant, so a variant that
        // declares the tag property itself cannot be read back.
        let mut inline_tags = BTreeSet::new();
        let tagged = branches.iter().all(|b| match b {
            RefOr::Ref(r) => struct_component(spec, &r.reference)
                .is_some_and(|s| !s.properties.contains_key(&d.property_name)),
            RefOr::Item(s) => {
                is_inline_object(b)
                    && inline_tag_value(s, &d.property_name)
                        .is_some_and(|tag| inline_tags.insert(tag))
            }
        });
        return if tagged {
            UnionPlan::Tagged(d.property_name.clone())
        } else {
            UnionPlan::Ambiguous
        };
    }
    if branches.iter().any(|b| is_inline_object(b)) {
        return inline_union_plan(branches, spec);
    }
    let mut refs = BTreeSet::new();
    let mut json_types = BTreeSet::new();
    for b in branches {
        let distinct = match b {
            RefOr::Ref(r) => {
                struct_component(spec, &r.reference).is_some() && refs.insert(r.reference.as_str())
            }
            RefOr::Item(s) => {
                primitive_branch(s).is_some_and(|(json, _, _)| json_types.insert(json))
            }
        };
        if !distinct {
            return UnionPlan::Ambiguous;
        }
    }
    if json_types.contains(&"integer") && json_types.contains(&"number") {
        return UnionPlan::Ambiguous;
    }
    UnionPlan::Untagged
}

/// An inline object branch: a schema with its own properties.
fn is_inline_object(b: &RefOr<Schema>) -> bool {
    matches!(b, RefOr::Item(s) if !s.properties.is_empty())
}

/// The tag value of an inline branch: the one JSON string in the `enum` of its
/// tag property. `None` when the property is missing, a `$ref`, or not a single value.
fn inline_tag_value<'a>(schema: &'a Schema, property: &str) -> Option<&'a str> {
    match schema.properties.get(property)? {
        RefOr::Item(p) => match p.enum_values.as_slice() {
            [v] => v.as_str(),
            _ => None,
        },
        RefOr::Ref(_) => None,
    }
}

/// A union with at least one inline object branch and no discriminator. It is
/// typed when every object-like branch (inline, or a `$ref` struct) has a
/// `required` list, and no branch's `required` names are all properties of another.
fn inline_union_plan(branches: &[&RefOr<Schema>], spec: &Spec) -> UnionPlan {
    let mut refs = BTreeSet::new();
    let mut json_types = BTreeSet::new();
    let mut objects: Vec<&Schema> = Vec::new();
    for b in branches {
        match b {
            RefOr::Ref(r) => {
                let Some(s) = struct_component(spec, &r.reference) else {
                    return UnionPlan::Ambiguous;
                };
                if !refs.insert(r.reference.as_str()) {
                    return UnionPlan::Ambiguous;
                }
                objects.push(s);
            }
            RefOr::Item(s) if is_inline_object(b) => objects.push(s),
            RefOr::Item(s) => {
                let Some((json, _, _)) = primitive_branch(s) else {
                    return UnionPlan::Ambiguous;
                };
                if !json_types.insert(json) {
                    return UnionPlan::Ambiguous;
                }
            }
        }
    }
    if json_types.contains(&"integer") && json_types.contains(&"number") {
        return UnionPlan::Ambiguous;
    }
    if objects.iter().any(|s| s.required.is_empty()) {
        return UnionPlan::Ambiguous;
    }
    for (i, a) in objects.iter().enumerate() {
        for (j, b) in objects.iter().enumerate() {
            if i != j && a.required.iter().all(|r| b.properties.contains_key(r)) {
                return UnionPlan::Ambiguous;
            }
        }
    }
    UnionPlan::Untagged
}

/// The struct name of an inline branch, as the Python emitter names it: the parent
/// and its one required property, or the parent and the branch position.
fn inline_struct_name(parent: &str, schema: &Schema, idx: usize) -> String {
    if schema.required.len() == 1 && schema.properties.contains_key(&schema.required[0]) {
        format!("{parent}{}", to_pascal(&schema.required[0]))
    } else {
        format!("{parent}Variant{}", idx + 1)
    }
}

/// The tag value for a variant: the mapping key whose value names the branch,
/// or the bare schema key when no mapping entry does.
fn variant_tag(schema: &Schema, reference: &str) -> String {
    let bare = reference.strip_prefix(SCHEMAS_PREFIX).unwrap_or(reference);
    schema
        .discriminator
        .as_ref()
        .and_then(|d| {
            d.mapping
                .iter()
                .find(|(_, v)| v.as_str() == reference || v.as_str() == bare)
                .map(|(k, _)| k.clone())
        })
        .unwrap_or_else(|| bare.to_string())
}

fn emit_union(
    key: &str,
    name: &str,
    schema: &Schema,
    spec: &Spec,
    tm: &TypeMap,
    target: RustTarget,
    warnings: &mut Vec<String>,
) -> String {
    let source = if schema.one_of.is_empty() {
        &schema.any_of
    } else {
        &schema.one_of
    };
    let branches: Vec<&RefOr<Schema>> = source.iter().filter(|b| !is_null_branch(b)).collect();
    let plan = union_plan(schema, &branches, spec);
    let header = match &plan {
        UnionPlan::Ambiguous => {
            warnings.push(format!(
                "schema `{key}` is a oneOf/anyOf that cannot be told apart; generated as serde_json::Value"
            ));
            return format!("pub type {name} = serde_json::Value;\n");
        }
        UnionPlan::Tagged(tag) => format!("#[serde(tag = \"{}\")]\n", esc(tag)),
        UnionPlan::Untagged => "#[serde(untagged)]\n".to_string(),
    };
    let tag_property = match &plan {
        UnionPlan::Tagged(property) => Some(property.as_str()),
        UnionPlan::Untagged | UnionPlan::Ambiguous => None,
    };
    let tagged = tag_property.is_some();

    let mut s = String::from("#[derive(Debug, Clone, Serialize, Deserialize)]\n");
    s.push_str(&header);
    s.push_str(&format!("pub enum {name} {{\n"));
    let mut reg = NameRegistry::new();
    let mut structs: Vec<String> = Vec::new();
    for (idx, branch) in source.iter().enumerate() {
        if is_null_branch(branch) {
            continue;
        }
        match branch {
            RefOr::Ref(r) => {
                let Some(ty) = tm.resolve_ref(&r.reference) else {
                    continue;
                };
                let variant = reg.unique(&ty);
                if tagged {
                    let tag = variant_tag(schema, &r.reference);
                    s.push_str(&format!("    #[serde(rename = \"{}\")]\n", esc(&tag)));
                }
                s.push_str(&format!("    {variant}({ty}),\n"));
            }
            RefOr::Item(p) if is_inline_object(branch) => {
                let sname = inline_struct_name(name, p, idx);
                match tag_property {
                    Some(property) => {
                        // The plan gives every inline branch one tag value.
                        let tag = inline_tag_value(p, property)
                            .expect("tagged plan has a tag value for each inline branch");
                        structs.push(emit_struct_skipping(&sname, p, tm, target, Some(property)));
                        s.push_str(&format!("    #[serde(rename = \"{}\")]\n", esc(tag)));
                    }
                    None => structs.push(emit_struct(&sname, p, tm, target)),
                }
                let variant = reg.unique(&sname);
                s.push_str(&format!("    {variant}({sname}),\n"));
            }
            RefOr::Item(p) => {
                let Some((_, variant, ty)) = primitive_branch(p) else {
                    continue;
                };
                let variant = reg.unique(variant);
                s.push_str(&format!("    {variant}({ty}),\n"));
            }
        }
    }
    s.push_str("}\n");
    if structs.is_empty() {
        return s;
    }
    format!("{}\n{s}", structs.join("\n"))
}

/// True when a component schema is a string enum eligible for a Rust enum definition.
fn is_string_enum(schema: &Schema) -> bool {
    schema.type_names().as_slice() == ["string"]
        && !schema.enum_values.is_empty()
        && schema.enum_values.iter().all(|v| v.is_string())
        && schema.properties.is_empty()
        && schema.one_of.is_empty()
        && schema.any_of.is_empty()
        && schema.all_of.is_empty()
}

fn emit_enum(name: &str, schema: &Schema) -> String {
    let mut s = String::from("#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n");
    s.push_str(&format!("pub enum {name} {{\n"));
    let mut reg = NameRegistry::new();
    for val in &schema.enum_values {
        if let Some(raw) = val.as_str() {
            let mut pascal = to_pascal(raw);
            if pascal == "Self" {
                pascal = "Self_".to_string();
            }
            let variant = reg.unique(&pascal);
            s.push_str(&format!("    #[serde(rename = \"{}\")]\n", esc(raw)));
            s.push_str(&format!("    {variant},\n"));
        }
    }
    s.push_str("}\n");
    s
}

fn emit_struct(name: &str, schema: &Schema, tm: &TypeMap, target: RustTarget) -> String {
    emit_struct_skipping(name, schema, tm, target, None)
}

/// Like `emit_struct`, but leaves out the property `skip`. An internally tagged
/// variant must not declare its tag: serde removes the tag before it reads the variant.
fn emit_struct_skipping(
    name: &str,
    schema: &Schema,
    tm: &TypeMap,
    target: RustTarget,
    skip: Option<&str>,
) -> String {
    let mut s = String::from("#[derive(Debug, Clone, Serialize, Deserialize)]\n");
    s.push_str(&format!("pub struct {name} {{\n"));
    for (key, prop) in &schema.properties {
        if skip == Some(key.as_str()) {
            continue;
        }
        let required = schema.required.iter().any(|r| r == key);
        let ty = rsmap::type_expr(prop, tm);
        let ty = if required { ty } else { rsmap::optional(&ty) };
        let (field, rename) = field_name(key, target);
        if let Some(orig) = rename {
            s.push_str(&format!("    #[serde(rename = \"{}\")]\n", esc(&orig)));
        }
        if !required && rsmap::is_free_form(&ty) {
            // `Value` is not wrapped in `Option`: a missing key and `null` both
            // decode to `Value::Null`, and `is_null` omits it on output.
            s.push_str(
                "    #[serde(default, skip_serializing_if = \"serde_json::Value::is_null\")]\n",
            );
        } else if !required {
            s.push_str("    #[serde(skip_serializing_if = \"Option::is_none\")]\n");
        }
        s.push_str(&format!("    pub {field}: {ty},\n"));
    }
    s.push_str("}\n");
    s
}

fn esc(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

