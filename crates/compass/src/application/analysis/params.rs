// Implement TryFrom for param types
impl TryFrom<serde_json::Value> for CheckParams {
    type Error = serde_json::Error;
    fn try_from(value: serde_json::Value) -> Result<Self, Self::Error> {
        serde_json::from_value(value)
    }
}

